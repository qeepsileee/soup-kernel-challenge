"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.
"""

def apply():
    from .swiglu import patch_qwen2_mlp
    from .nf4 import patch_dequantize
    from .nf4_linear import patch_linear
    from .rmsnorm import patch_rmsnorm
    from .entropy import patch_entropy
    from .mlp_bridge import patch_mlp_bridge
    from .lora_fusion import patch_lora
    from .patch_chunked_loss import patch_chunked_loss
    from .compressed_mlp import patch_compressed_mlp
    from .half_storage import patch_half_storage

    patch_qwen2_mlp()  # the example: works out of the box, does not count as your own kernel
    patch_dequantize()  # participant 3: validated NF4 decoder; retain bnb matmul
    patch_linear()  # decode in forward/backward, cuBLAS performs all matrix products
    patch_rmsnorm()  # independent frozen-weight fusion; coordinate with participant 2
    patch_entropy()  # memory-light metric; coordinate with participant 1
    patch_mlp_bridge()  # avoid widening/narrowing frozen MLP activations
    patch_lora()  # selective: wide q-like projections with >=2048 token rows
    patch_chunked_loss()  # fused Triton CE: eliminates full [B,T,V] logits tensor
    patch_compressed_mlp()  # INT8 saved activations; validated on the public task
    patch_half_storage()  # opt-in experiment; off unless explicitly requested
    # Both custom dX GEMM experiments regressed on T4. Keep them opt-in via
    # bench_nf4 flags, never activate them in the normal training entry point.
